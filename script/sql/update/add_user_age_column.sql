-- =============================================================
-- 为用户表添加年龄字段并设置默认值
-- =============================================================

-- 1. 为sys_user表添加age字段，设置为必填，默认值为0
ALTER TABLE sys_user ADD COLUMN age INT NOT NULL DEFAULT 0 COMMENT '年龄';

-- 2. 更新所有已有用户的年龄为0（新增字段时已有默认值，此步骤为确保数据一致性）
UPDATE sys_user SET age = 0 WHERE age IS NULL OR age < 0;

